import { zodiacSign } from './zodiac';

describe('zodiacSign', () => {
  it.each([
    [1, 1, 'Козерог'],
    [1, 19, 'Козерог'],
    [1, 20, 'Водолей'],
    [2, 29, 'Рыбы'],
    [4, 20, 'Телец'],
    [5, 19, 'Телец'],
    [5, 21, 'Близнецы'],
    [10, 23, 'Весы'],
    [10, 24, 'Скорпион'],
    [12, 21, 'Стрелец'],
    [12, 22, 'Козерог'],
    [12, 31, 'Козерог'],
  ])('%i.%i → %s', (month, day, name) => {
    expect(zodiacSign({ month, day }).name).toBe(name);
  });
});
